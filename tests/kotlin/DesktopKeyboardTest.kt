package app.polarbear

fun main() {
    val events = mutableListOf<Pair<Int, Boolean>>()
    val state = DesktopKeyboardState({ code, down -> events += code to down })
    fun expect(vararg wanted: Pair<Int, Boolean>) { check(events == wanted.toList()) { "$events != ${wanted.toList()}" }; events.clear() }
    state.tap(29); check(state.level(29) == 1)
    state.tap(46); check(state.level(29) == 0)
    expect(29 to true, 46 to true, 46 to false, 29 to false)
    state.tap(56); state.tap(56); check(state.level(56) == 2)
    state.tap(15); state.tap(15); state.tap(56)
    expect(56 to true, 15 to true, 15 to false, 15 to true, 15 to false, 56 to false)
    state.press(42); state.press(30); state.release(30); state.release(42)
    check(state.level(42) == 0)
    expect(42 to true, 30 to true, 30 to false, 42 to false)
    state.press(29); state.release(29, cancelled = true)
    expect()
    state.press(125); state.release(125, cancelled = true)
    expect() // A swipe from Super must not open the desktop launcher.
    state.press(106); state.press(42); state.release(42); state.release(106)
    expect(106 to true, 42 to true, 42 to false, 106 to false)
    state.tap(29); state.tap(42); state.press(46); state.press(47); state.release(46)
    check(state.level(29) == 1 && state.level(42) == 1)
    state.release(47)
    expect(29 to true, 42 to true, 46 to true, 47 to true, 46 to false, 47 to false, 42 to false, 29 to false)
    state.shortcut(29, 42, 46)
    expect(29 to true, 42 to true, 46 to true, 46 to false, 42 to false, 29 to false)
    state.tap(29); state.press(30); state.reset(); state.release(30); state.release(29)
    expect(29 to true, 30 to true, 30 to false, 29 to false)
    state.press(29); state.shortcut(56, 15); state.release(29, true)
    expect()
    state.press(14); state.press(14); state.release(14); state.release(14)
    expect(14 to true, 14 to false)
    // Releasing a modifier before the letter must retain the original chord.
    state.press(29); state.press(46); state.release(29); state.release(46)
    expect(29 to true, 46 to true, 29 to false, 46 to false)
    state.tap(54); check(state.level(54) == 1)
    state.press(30); state.release(30)
    expect(54 to true, 30 to true, 30 to false, 54 to false)
    // A locked modifier remains visibly locked while touched and survives a cancelled swipe.
    state.tap(42); state.tap(42); state.press(42)
    check(state.level(42) == 2)
    state.release(42, cancelled = true); check(state.level(42) == 2)
    state.reset()
    expect(42 to true, 42 to false)
    // Lock keys belong to the desktop; closing the surface must not flip them off.
    state.tap(58); check(state.capsLock && state.level(58) == 2)
    state.reset(); check(state.capsLock)
    state.tap(58); check(!state.capsLock)
    expect(58 to true, 58 to false, 58 to true, 58 to false)
    check(DesktopKeyboardLayout.letters[0].first().code == 15)
    check(DesktopKeyboardLayout.letters[1].first().code == 58)
    check(DesktopKeyboardLayout.letters[1].last().code == 28)
    check(DesktopKeyboardLayout.letters[2].first().code == 42)
    check(DesktopKeyboardLayout.bottom.first().code == 1)
    check(DesktopKeyboardLayout.functions.map { it.code } == (59..68).toList() + listOf(87, 88))
    val all = DesktopKeyboardLayout.letters.flatten() + DesktopKeyboardLayout.symbols.flatten() + DesktopKeyboardLayout.numbers +
        DesktopKeyboardLayout.bottom + DesktopKeyboardLayout.functions + DesktopKeyboardLayout.navigation + DesktopKeyboardLayout.system + DesktopKeyboardLayout.numpad.flatten()
    check(all.all { it.code in 1..127 })
    check(DesktopKeyboardLayout.letters.all { it.map { k -> k.code }.distinct().size == it.size })
    println("Desktop keyboard: sticky modifiers, multi-touch, shortcuts, cancellation, reset, and key mappings passed")
}
